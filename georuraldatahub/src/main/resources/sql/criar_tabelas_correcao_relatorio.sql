-- =========================================================
-- TABELA: CORRECAO
-- Entidade Java: Correction
-- =========================================================

CREATE TABLE correcao (
    cor_id NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY
        NOT NULL,

    arq_id NUMBER(19) NOT NULL,
    usr_id NUMBER(19) NOT NULL,

    cor_campo VARCHAR2(255),
    cor_valor_original VARCHAR2(4000),
    cor_valor_proposto VARCHAR2(4000),

    cor_status VARCHAR2(30) DEFAULT 'RASCUNHO' NOT NULL,

    cor_data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    cor_data_atualizacao TIMESTAMP,

    CONSTRAINT pk_correcao PRIMARY KEY (cor_id),

    CONSTRAINT fk_correcao_arquivo
        FOREIGN KEY (arq_id)
        REFERENCES arquivo(arq_id),

    CONSTRAINT fk_correcao_usuario
        FOREIGN KEY (usr_id)
        REFERENCES usuario(usr_id)
);


-- =========================================================
-- TABELA: RELATORIO_INCONSISTENCIA
-- Entidade Java: Report
-- =========================================================

CREATE TABLE relatorio_inconsistencia (
    rel_id NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY
        NOT NULL,

    arq_id NUMBER(19) NOT NULL,
    usr_id NUMBER(19) NOT NULL,

    rel_titulo VARCHAR2(200) NOT NULL,
    rel_conteudo CLOB NOT NULL,

    rel_status VARCHAR2(20) DEFAULT 'RASCUNHO' NOT NULL,

    rel_criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    rel_atualizado_em TIMESTAMP,
    rel_finalizado_em TIMESTAMP,

    CONSTRAINT pk_relatorio_inconsistencia PRIMARY KEY (rel_id),

    CONSTRAINT fk_relatorio_arquivo
        FOREIGN KEY (arq_id)
        REFERENCES arquivo(arq_id),

    CONSTRAINT fk_relatorio_usuario
        FOREIGN KEY (usr_id)
        REFERENCES usuario(usr_id)
);