CREATE TABLE resultado_indicador (
    rin_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rin_codigo VARCHAR2(100 CHAR) NOT NULL,
    con_id NUMBER NOT NULL,
    cam_id NUMBER NULL,
    rin_referencia_imovel VARCHAR2(150 CHAR) NULL,
    rin_unidade VARCHAR2(50 CHAR) NULL,
    rin_dados CLOB NOT NULL,
    rin_calculado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_rin_conjunto FOREIGN KEY (con_id) REFERENCES conjunto (con_id),
    CONSTRAINT fk_rin_camada FOREIGN KEY (cam_id) REFERENCES camada (cam_id)
);

CREATE INDEX idx_rin_conjunto ON resultado_indicador (con_id);
CREATE INDEX idx_rin_codigo ON resultado_indicador (rin_codigo);
CREATE INDEX idx_rin_imovel ON resultado_indicador (rin_referencia_imovel);
